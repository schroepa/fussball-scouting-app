/** Komfort-API für typische String-Selects (kein natives &lt;select&gt;). */
function SimpleSelect({
  value,
  onValueChange,
  options,
  placeholder,
  className,
  size = "default",
  id,
  disabled,
  name,
}: {
  value: string
  onValueChange: (value: string) => void
  options: { value: string; label: string }[]
  placeholder?: string
  className?: string
  size?: "sm" | "default"
  id?: string
  disabled?: boolean
  name?: string
}) {
  const items = React.useMemo(
    () => [
      ...(placeholder ? [{ value: null as string | null, label: placeholder }] : []),
      ...options.map((o) => ({ value: o.value, label: o.label })),
    ],
    [options, placeholder]
  )

  return (
    <Select
      value={value === "" ? null : value}
      onValueChange={(next) => onValueChange(next ?? "")}
      items={items}
      disabled={disabled}
      name={name}
      id={id}
    >
      <SelectTrigger className={className} size={size}>
        <SelectValue />
      </SelectTrigger>
      <SelectContent>
        {items.map((item) => (
          <SelectItem key={String(item.value)} value={item.value}>
            {item.label}
          </SelectItem>
        ))}
      </SelectContent>
    </Select>
  )
}

